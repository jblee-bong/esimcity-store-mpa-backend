-- 포켓와이파이 MCC → 나라 표 (관리자 > 포켓와이파이 > 나라(MCC) 표 에서 수정). mcc '-' = MCC 없이 나라만 (괌·사이판 직접 지정용)
CREATE TABLE IF NOT EXISTS TB_WIFI_MCC (
    id        BIGINT       NOT NULL AUTO_INCREMENT,
    mcc       VARCHAR(10)  NOT NULL COMMENT 'MCC 3자리, 없으면 -',
    iso       CHAR(2)      NOT NULL COMMENT '나라 ISO 2글자',
    name      VARCHAR(50)  NOT NULL COMMENT '한국어 나라 이름',
    modify_dt DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_wifi_mcc (mcc, iso)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='포켓와이파이 MCC 나라 표';

